# B-only, offline, fixed CC roots. Never invoked by Install/Start/Verify.
[CmdletBinding()]
param([switch]$Execute, [switch]$SealFreshCCFiles, [string]$PanelSid,
      [string]$Archive, [string]$SupportingMedia)
. "$PSScriptRoot\Common.ps1"
if (-not $Execute) {
    Write-Output 'PREVIEW: verify pinned PythonCore ZIP and private B approval; populate only initially empty CC runtime. Explicit -Execute -SealFreshCCFiles required. No Python execution, users, system ACL, registry, PATH, Task or trading changes.'
    return
}
if (-not ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.SecurityIdentifier]::new('S-1-5-32-544'))) { throw 'B_ADMIN_INSTALL_TOKEN_REQUIRED' }
if (-not $SealFreshCCFiles) { throw 'DISTINCT_FRESH_CC_SEAL_APPROVAL_REQUIRED' }
Assert-RuntimeBoundary $PanelSid
Assert-LayoutACL $PanelSid
$manifest = Get-Manifest $script:PackageRoot
foreach ($root in @($script:RuntimeRoot,$script:AppRoot,$script:VenvRoot)) {
    if (@(Get-ChildItem -Force -LiteralPath $root).Count) { throw 'EMPTY_CC_TARGET_REQUIRED' }
}
# Approval is installed separately after review, never generated by this script.
$approvalPath = Join-Path $script:DataRoot 'private\pythoncore-b-approval.json'
Assert-ACL $approvalPath $PanelSid 'private'
$approval = Get-Content -Raw -LiteralPath $approvalPath | ConvertFrom-Json
if ($approval.schema_id -cne 'cc03.pythoncore-b-approval.v1' -or $approval.b_execution_approved -ne $true -or
    $approval.seal_fresh_cc_files_approved -ne $true -or $approval.panel_sid -cne $PanelSid -or
    $approval.archive_sha256 -cne $script:PythonCoreHash -or
    $approval.package_manifest_sha256 -cne (Get-FileHash -LiteralPath "$script:PackageRoot\deployment\manifest.json" -Algorithm SHA256).Hash.ToLowerInvariant() -or
    [string]::IsNullOrWhiteSpace($approval.review_reference)) { throw 'INDEPENDENT_B_APPROVAL_REQUIRED' }
foreach ($inputPath in @($Archive,$SupportingMedia)) {
    if ([string]::IsNullOrWhiteSpace($inputPath)) { throw 'OFFLINE_CC_MEDIA_REQUIRED' }
    $full = [IO.Path]::GetFullPath($inputPath)
    if (-not $full.StartsWith($script:ControlCenterRoot+'\',[StringComparison]::OrdinalIgnoreCase)) { throw 'CC_ONLY_MEDIA_REQUIRED' }
    Assert-PlainPath $full
    Assert-TreeACL $full $PanelSid
    $parent = [IO.DirectoryInfo]::new((Split-Path $full -Parent))
    while ($parent.FullName -ne $script:ControlCenterRoot) {
        Assert-ACL $parent.FullName $PanelSid 'app'
        $parent = $parent.Parent
    }
}
# Hold both actual source files against replacement/write through the transaction.
$zipStream = [IO.File]::Open($Archive,[IO.FileMode]::Open,[IO.FileAccess]::Read,[IO.FileShare]::Read)
$mediaStream = $null
$created = [Collections.Generic.List[string]]::new()
function New-OwnedDirectory([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path)) {
        $null = New-Item -ItemType Directory -Path $Path
        $created.Add($Path)
    }
    Assert-PlainPath $Path
}
function Write-OwnedStream([string]$Path, [IO.Stream]$InputStream) {
    Assert-PlainPath $Path
    $output = [IO.File]::Open($Path,[IO.FileMode]::CreateNew,[IO.FileAccess]::Write,[IO.FileShare]::None)
    $created.Add($Path)
    try { $InputStream.CopyTo($output) } finally { $output.Dispose() }
}
function Protect-FreshCCFiles {
    # Distinct, explicitly approved sealing step. Only this transaction's new
    # paths, never repairs existing roots, old staging or system/robot ACLs.
    foreach ($path in $created) {
        Assert-PlainPath $path
        $acl = Get-Acl -LiteralPath $path
        $acl.SetOwner([Security.Principal.SecurityIdentifier]::new('S-1-5-32-544'))
        if ($path -eq $script:BaseRoot -or $path -eq $script:RuntimeProvenance) { $acl.SetAccessRuleProtection($true,$true) }
        Set-Acl -LiteralPath $path -AclObject $acl
        Assert-TreeACL $path $PanelSid
    }
}
try {
    $records = @(Get-PythonCoreInventory $zipStream)
    $mediaStream = [IO.File]::Open($SupportingMedia,[IO.FileMode]::Open,[IO.FileAccess]::Read,[IO.FileShare]::Read)
    Assert-SupportingPythonMedia $SupportingMedia $approval.supporting_media_sha256
    # Nothing above writes to any target. All below are fresh CreateNew paths.
    New-OwnedDirectory $script:BaseRoot
    $zipStream.Position = 0
    Write-OwnedStream (Join-Path $script:RuntimeRoot 'python-3.12.10-amd64.zip') $zipStream
    Write-OwnedStream (Join-Path $script:RuntimeRoot 'python-3.12.10-amd64.exe') $mediaStream
    $zipStream.Position = 0
    $zip = [IO.Compression.ZipArchive]::new($zipStream,[IO.Compression.ZipArchiveMode]::Read,$true)
    try {
        foreach ($record in $records) {
            $target = Join-Path $script:BaseRoot $record.path
            $relativeParent = Split-Path $record.path -Parent
            $current = $script:BaseRoot
            foreach ($part in ($relativeParent -split '[/\\]' | Where-Object { $_ })) {
                $current = Join-Path $current $part
                New-OwnedDirectory $current
            }
            $entry = $zip.GetEntry($record.path)
            $inputStream = $entry.Open()
            try { Write-OwnedStream $target $inputStream } finally { $inputStream.Dispose() }
            if ((Get-FileHash -LiteralPath $target -Algorithm SHA256).Hash.ToLowerInvariant() -cne $record.sha256 -or
                (Get-Item -LiteralPath $target).Length -ne $record.size) { throw 'EXTRACTED_FILE_HASH_MISMATCH' }
        }
    } finally { $zip.Dispose() }
    $provenance = @{schema_id='cc03.python-base.v2';b_only_approved=$true;release='CPython-3.12.10-amd64-full';
        distribution_id='pythoncore-3.12-64';source_uri=$script:PythonCoreUri;archive_sha256=$script:PythonCoreHash;
        archive_size=$script:PythonCoreSize;review_reference=$approval.review_reference;files=$records;
        supporting_media=@{source_uri='https://www.python.org/ftp/python/3.12.10/python-3.12.10-amd64.exe';sha256=$approval.supporting_media_sha256}}
    $bytes = [Text.Encoding]::UTF8.GetBytes(($provenance | ConvertTo-Json -Depth 6))
    $jsonStream = [IO.MemoryStream]::new($bytes,$false)
    try { Write-OwnedStream $script:RuntimeProvenance $jsonStream } finally { $jsonStream.Dispose() }
    Protect-FreshCCFiles
    $actual = @(Get-PlainTree $script:BaseRoot | Where-Object { -not $_.PSIsContainer } | ForEach-Object {
        @{path=$_.FullName.Substring($script:BaseRoot.Length+1).Replace('\','/');size=$_.Length;
          sha256=(Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant()}
    })
    Assert-PythonCoreManifest $records $actual
    Write-Output 'CC03_PYTHONCORE_PROVISIONED_NO_PYTHON_EXECUTED: B runtime tests and physical ACL acceptance remain separate'
} catch {
    $failure = $_
    # Validate ALL owned paths before deleting any. No recursion, no wildcards,
    # no removal of pre-existing roots or unexpected/injected directory contents.
    foreach ($path in $created) { Assert-PlainPath $path }
    for ($i=$created.Count-1; $i -ge 0; $i--) {
        $path = $created[$i]
        if (Test-Path -LiteralPath $path -PathType Container) { [IO.Directory]::Delete($path,$false) }
        else { [IO.File]::Delete($path) }
    }
    throw $failure
} finally {
    $zipStream.Dispose()
    if ($null -ne $mediaStream) { $mediaStream.Dispose() }
}
